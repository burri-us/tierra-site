#!/usr/bin/env python3
"""Generate assets/tokens.css from design/tokens.json (the Tierra design system, single source).

Usage: python tools/gen_tokens.py          write assets/tokens.css
       python tools/gen_tokens.py --check  fail if assets/tokens.css is out of date or tokens.json differs from the recorded SHA-256
Never edit assets/tokens.css by hand.
"""
import hashlib, json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "design" / "tokens.json"
SHA_FILE = ROOT / "design" / "tokens.sha256"
OUT = ROOT / "assets" / "tokens.css"

# Self-hosted faces (woff2, SIL OFL 1.1; see THIRD-PARTY-NOTICES.md). Only the weights the site uses.
FACES = [
    ("Inter", 400, "inter-latin-400-normal.woff2"),
    ("Inter", 600, "inter-latin-600-normal.woff2"),
    ("Space Grotesk", 400, "space-grotesk-latin-400-normal.woff2"),
    ("Space Grotesk", 600, "space-grotesk-latin-600-normal.woff2"),
    ("Space Grotesk", 700, "space-grotesk-latin-700-normal.woff2"),
    ("JetBrains Mono", 400, "jetbrains-mono-latin-400-normal.woff2"),   # code and licence text (--font-mono)
]

def build():
    t = json.loads(SRC.read_text(encoding="utf-8"))
    tokens = {x["name"]: x["value"] for x in t["color"]["tokens"]}
    def val(name, theme):
        v = tokens[name]
        if isinstance(v, str):
            return val(v.strip("{}"), theme)
        return v[theme]
    names = [x["name"] for x in t["color"]["tokens"]]
    lines = ["/* GENERATED by tools/gen_tokens.py from design/tokens.json (Tierra Design System v%s). Do not edit by hand. */" % t["version"]]
    for fam, w, f in FACES:
        lines.append('@font-face { font-family: "%s"; font-style: normal; font-weight: %d; font-display: swap; src: url("/assets/fonts/%s") format("woff2"); }' % (fam, w, f))
    lines.append(":root {")
    for n in names:
        lines.append("  --%s: %s;" % (n, val(n, "light")))
    for k, v in t["type"]["families"].items():
        lines.append("  --font-%s: %s;" % (k, v))
    for g in t["type"]["groups"]:
        for s in g["styles"]:
            p = "--type-" + s["name"]
            lines.append("  %s-size: %s; %s-line: %s; %s-weight: %s;" % (p, s["fontSize"], p, s["lineHeight"], p, s["fontWeight"]))
            if "letterSpacing" in s:
                lines.append("  %s-tracking: %s;" % (p, s["letterSpacing"]))
    for grp in ("spacing", "radius", "size", "shadow"):
        for x in t[grp]["tokens"]:
            lines.append("  --%s: %s;" % (x["name"], x["value"]))
    lines.append("}")
    lines.append("@media (prefers-color-scheme: dark) {\n  :root {")
    for n in names:
        if isinstance(tokens[n], dict):
            lines.append("    --%s: %s;" % (n, val(n, "dark")))
    lines.append("  }\n}")
    return "\n".join(lines) + "\n"

def sha():
    return hashlib.sha256(SRC.read_bytes()).hexdigest()

def main():
    if "--check" in sys.argv:
        bad = []
        recorded = SHA_FILE.read_text().split()[0] if SHA_FILE.exists() else ""
        if recorded != sha():
            bad.append("design/tokens.json does not match design/tokens.sha256")
        if not OUT.exists() or OUT.read_bytes().decode("utf-8").replace("\r\n", "\n") != build():
            bad.append("assets/tokens.css is out of date: run python tools/gen_tokens.py")
        for b in bad:
            print("FAIL", b)
        return 1 if bad else 0
    OUT.write_bytes(build().encode("utf-8"))
    SHA_FILE.write_text(sha() + "  tokens.json\n")
    print("wrote", OUT.relative_to(ROOT))
    return 0

if __name__ == "__main__":
    sys.exit(main())
